export type DictKey = keyof typeof DICT["pt-BR"];

export function t(locale: Locale, key: DictKey, fallback?: string): string {
  return (DICT[locale] as Record<string, string>)[key] ?? fallback ?? key;
}

/** Substitui {placeholders} simples (sem plural). */
export function tf(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
